import fs from "node:fs";
import path from "node:path";

const root = path.resolve(import.meta.dirname, "..");
const sitesDir = path.join(root, "sites");
const ids = fs
  .readdirSync(sitesDir, { withFileTypes: true })
  .filter((entry) => entry.isDirectory() && fs.existsSync(path.join(sitesDir, entry.name, "site.json")))
  .map((entry) => entry.name)
  .sort();

const imports = ids
  .map((id) => {
    const ident = id.replace(/[^a-z0-9]+/gi, "_");
    return [
      `import ${ident}Site from "../../sites/${id}/site.json";`,
      `import ${ident}Features from "../../sites/${id}/features.json";`,
      `import ${ident}Sources from "../../sites/${id}/sources.json";`,
    ].join("\n");
  })
  .join("\n");

const rows = ids
  .map((id) => {
    const ident = id.replace(/[^a-z0-9]+/gi, "_");
    return `  { site: ${ident}Site, features: ${ident}Features, sources: ${ident}Sources },`;
  })
  .join("\n");

const source = `/* Generated by scripts/generate-registry.mjs. Do not edit by hand. */
${imports}

export const sitePackages = [
${rows}
] as const;
`;

const target = path.join(root, "src/lib/site-registry.generated.ts");
fs.writeFileSync(target, source);
console.log(`registry: ${ids.join(", ") || "(none)"}`);
